// spec is a code's fixed transport mapping: the connect.Code an RPC handler
// returns for it and the canonical HTTP status REST uses when the caller does
// not choose one (Respond / FromError). The table is closed: TestCatalogCoversEveryCode
// fails when a constant in codes.go has no row or a row names no constant.
//
// The canonical HTTP status of each pre-existing code is the status its call
// sites used most often when the catalog was built (ADR-0012); the connect.Code
// follows from that status (see ConnectCodeForHTTPStatus) except where the
// code's meaning is narrower than its status (AlreadyExists, Aborted,
// Canceled, ResourceExhausted).
type spec struct {
	connect connect.Code
	status  int
}

