#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outputPath = join(root, "docs", "cli.md");
const write = process.argv.includes("--write");
const temp = mkdtempSync(join(tmpdir(), "astronomer-cli-docs-"));
const binary = join(temp, "astro");

function run(args) {
  return execFileSync(binary, [...args, "--help"], {
    cwd: root,
    encoding: "utf8",
    env: { ...process.env, NO_COLOR: "1" },
  }).trimEnd();
}

function childCommands(help) {
  const lines = help.split("\n");
  const start = lines.findIndex((line) => line.trim() === "Available Commands:");
  if (start < 0) return [];
  const children = [];
  for (const line of lines.slice(start + 1)) {
    if (line.trim() === "") continue;
    if (!/^\s/.test(line)) break;
    const match = line.match(/^\s{2,}([a-z][a-z0-9-]*)\s{2,}/);
    if (match && match[1] !== "help") children.push(match[1]);
  }
  return children;
}

function renderCommand(args, seen, sections) {
  const key = args.join(" ");
  if (seen.has(key)) return;
  seen.add(key);
  const help = run(args);
  const title = ["astro", ...args].join(" ");
  sections.push(`## \`${title}\`\n\n\`\`\`text\n${help}\n\`\`\``);
  for (const child of childCommands(help)) {
    renderCommand([...args, child], seen, sections);
  }
}

try {
  execFileSync("go", ["build", "-o", binary, "./cmd/astro"], {
    cwd: root,
    stdio: "inherit",
  });
  const sections = [];
  renderCommand([], new Set(), sections);
  const generated = `# astro CLI reference

<!-- Code generated by scripts/generate-cli-docs.mjs; DO NOT EDIT. -->

This reference is generated from the shipped Cobra command tree. The CLI uses the same public API as the dashboard; use \`astro docs\` to locate or print the live OpenAPI document.

${sections.join("\n\n")}
`;

  if (write) {
    writeFileSync(outputPath, generated);
    process.stdout.write(`wrote ${outputPath}\n`);
  } else {
    let current = "";
    try {
      current = readFileSync(outputPath, "utf8");
    } catch {
      // The comparison below provides the actionable error.
    }
    if (current !== generated) {
      process.stderr.write(
        "CLI docs are stale; run `make cli-docs` and commit docs/cli.md.\n",
      );
      process.exitCode = 1;
    } else {
      process.stdout.write("CLI docs are current.\n");
    }
  }
} finally {
  rmSync(temp, { recursive: true, force: true });
}
