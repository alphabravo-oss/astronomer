#!/usr/bin/env python3
"""Generate isolated legacy sqlc extensions from reviewable templates."""

from __future__ import annotations

import argparse
import os
import pathlib
import sys
import tempfile


ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "internal" / "db" / "queryextensions"
OUTPUT_DIR = ROOT / "internal" / "db" / "sqlc"
MARKER = "// Code generated by scripts/generate-sqlc-extensions.py; DO NOT EDIT."


def render(template: pathlib.Path) -> str:
    body = template.read_text(encoding="utf-8")
    if "package sqlc" not in body:
        raise ValueError(f"{template}: template must declare package sqlc")
    relative = template.relative_to(ROOT)
    return f"{MARKER}\n// Source: {relative}\n\n{body}"


def expected_outputs() -> dict[pathlib.Path, str]:
    templates = sorted(SOURCE_DIR.glob("*.go.tmpl"))
    if not templates:
        raise ValueError(f"no extension templates found under {SOURCE_DIR}")
    return {
        OUTPUT_DIR / template.name.removesuffix(".tmpl"): render(template)
        for template in templates
    }


def generated_outputs() -> set[pathlib.Path]:
    result: set[pathlib.Path] = set()
    for path in OUTPUT_DIR.glob("*.go"):
        try:
            first_line = path.read_text(encoding="utf-8").splitlines()[0]
        except (IndexError, UnicodeDecodeError):
            continue
        if first_line == MARKER:
            result.add(path)
    return result


def atomic_write(path: pathlib.Path, payload: str) -> None:
    descriptor, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(payload)
        os.replace(temporary_name, path)
    finally:
        if os.path.exists(temporary_name):
            os.unlink(temporary_name)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("write", "check"))
    args = parser.parse_args()

    try:
        expected = expected_outputs()
    except ValueError as error:
        print(f"sqlc-extensions: {error}", file=sys.stderr)
        return 1

    stale = generated_outputs() - set(expected)
    if args.mode == "write":
        for path, payload in expected.items():
            atomic_write(path, payload)
        for path in stale:
            path.unlink()
        print(f"sqlc-extensions: generated {len(expected)} isolated extensions")
        return 0

    mismatched = []
    for path, payload in expected.items():
        try:
            current = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            mismatched.append(str(path.relative_to(ROOT)))
            continue
        if current != payload:
            mismatched.append(str(path.relative_to(ROOT)))
    if stale:
        mismatched.extend(str(path.relative_to(ROOT)) for path in sorted(stale))
    if mismatched:
        print(
            "sqlc-extensions: generated output is stale: " + ", ".join(sorted(mismatched)),
            file=sys.stderr,
        )
        return 1
    print(f"sqlc-extensions: {len(expected)} isolated extensions are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
