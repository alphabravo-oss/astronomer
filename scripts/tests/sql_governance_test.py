import copy
import importlib.util
import json
import pathlib
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location("sql_gate", ROOT / "scripts/check-sql-governance.py")
GATE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(GATE)


class SQLGovernancePolicyTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.policy = json.loads(GATE.POLICY.read_text())
        cls.actual = GATE.inventory()

    def test_current_exact_source(self):
        self.assertTrue(GATE.verify(self.policy, self.actual))

    def reject(self, change):
        policy, actual = copy.deepcopy(self.policy), copy.deepcopy(self.actual)
        change(policy, actual)
        with self.assertRaises(ValueError):
            GATE.verify(policy, actual)

    def test_boolean_schema_is_not_integer_one(self):
        self.reject(lambda p, a: p.update(schema_version=True))

    def test_missing_owner(self):
        self.reject(lambda p, a: p["owners"].pop())

    def test_changed_module_helper_or_constant(self):
        self.reject(lambda p, a: p["owners"][0].update(source_sha256="0" * 64))

    def test_same_call_changed_builder_declaration(self):
        self.reject(lambda p, a: a["sites"][0].update(scope_sha256="0" * 64))

    def test_new_query_or_parameter(self):
        self.reject(lambda p, a: a["sites"].append({**a["sites"][0], "sha256": "0" * 64}))

    def test_removed_statement_is_not_silently_authorized(self):
        self.reject(lambda p, a: a["sites"].pop())

    def test_unknown_builder_is_not_blanket_allowlist(self):
        self.reject(lambda p, a: p["builders"][0].update(name="arbitrary-sql"))

    def test_missing_builder_dependency(self):
        self.reject(lambda p, a: p["builders"][0]["paths"].pop())

    def test_legacy_allowance_cannot_grow(self):
        self.reject(lambda p, a: p.update(legacy_site_ceiling=0))
        self.reject(lambda p, a: p.update(legacy_site_ceiling=GATE.MAX_LEGACY_SITES + 1))

    def test_actual_go_delete_and_generated_name_bypass_discovered(self):
        with tempfile.TemporaryDirectory() as directory:
            root = pathlib.Path(directory)
            for name in ("internal", "cmd", "pkg"):
                (root / name).mkdir()
            (root / "internal/runtime.gen.go").write_text("package runtime\nfunc run(){ db.Exec(ctx, `DELETE FROM new_sensitive_rows WHERE id=$1`,id) }\n")
            actual = GATE.inventory(root)
            self.assertIn("new_sensitive_rows", {t for site in actual["sites"] for t in site["delete_targets"]})
            with self.assertRaises(ValueError):
                GATE.verify(self.policy, actual)

    def test_actual_dormant_alias_activation_discovered(self):
        with tempfile.TemporaryDirectory() as directory:
            root = pathlib.Path(directory)
            for name in ("internal", "cmd", "pkg"):
                (root / name).mkdir()
            (root / "internal/activation.go").write_text("package runtime\nfunc run(){ prune := db.PruneOldImageVulnerabilityReportSnapshots; prune(ctx,cutoff) }\n")
            actual = GATE.inventory(root)
            self.assertTrue(any(site["operation"] == "StoppedActivation" for site in actual["sites"]))
            with self.assertRaises(ValueError):
                GATE.verify(self.policy, actual)

    def test_forged_generated_header_cannot_hide_new_sql_file(self):
        with tempfile.TemporaryDirectory() as directory:
            root = pathlib.Path(directory)
            output = root / "internal/db/sqlc"
            output.mkdir(parents=True)
            (output / "unowned.sql.go").write_text("// Code generated by sqlc. DO NOT EDIT.\npackage sqlc\nfunc run(){db.Exec(ctx,query)}")
            with self.assertRaises(ValueError):
                GATE.check_generated_namespace(root)

    def test_dormant_activation_cannot_receive_non_sql_annotation(self):
        def change(policy, actual):
            policy["sites"][0]["operation"] = "StoppedActivation"
            actual["sites"][0]["operation"] = "StoppedActivation"
        self.reject(change)

    def test_dynamic_delete_has_no_generic_builder_allowance(self):
        self.reject(lambda p, a: a["sites"][0].update(dynamic_delete=True))

    def test_actual_nested_sqlc_and_testdata_paths_are_not_exemptions(self):
        for namespace in ("internal/handler/sqlc", "internal/service/testdata"):
            with self.subTest(namespace=namespace), tempfile.TemporaryDirectory() as directory:
                root = pathlib.Path(directory)
                for name in (namespace, "cmd", "pkg"):
                    (root / name).mkdir(parents=True)
                (root / namespace / "runtime.go").write_text("package runtime\nfunc run(){ db.Exec(ctx, `DELETE FROM directory_escape WHERE id=$1`,id) }\n")
                actual = GATE.inventory(root)
                self.assertIn("directory_escape", {t for site in actual["sites"] for t in site["delete_targets"]})
                with self.assertRaises(ValueError):
                    GATE.verify(self.policy, actual)


if __name__ == "__main__":
    unittest.main()
