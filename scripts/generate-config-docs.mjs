#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "internal/config/config.go");
const outputPath = path.join(root, "docs/configuration.md");
const environmentPath = path.join(root, ".env.example");
const sessionPolicy = fs.readFileSync(
  path.join(root, "internal/sessionpolicy/session_timeout.go"),
  "utf8",
);
const sessionDefault = sessionPolicy.match(/\bDefaultMinutes\s*=\s*(\d+)/)?.[1];
if (!sessionDefault)
  throw new Error("cannot resolve sessionpolicy.DefaultMinutes");

function literalDefault(raw) {
  if (raw === "sessionpolicy.DefaultMinutes") return sessionDefault;
  if (raw.startsWith('"')) return JSON.parse(raw);
  const shift = raw.match(/^int64\((\d+)\s*<<\s*(\d+)\)$/);
  if (shift) return String(BigInt(shift[1]) << BigInt(shift[2]));
  if (/^(true|false|-?\d+(\.\d+)?)$/.test(raw)) return raw;
  throw new Error(`unsupported environment default: ${raw}`);
}

export function parseFields(source) {
  const fields = [];
  const pattern =
    /^\s*([A-Z][A-Za-z0-9_]*)\s+([^\s]+)\s+`mapstructure:"([^"]+)"`/gm;
  for (const match of source.matchAll(pattern)) {
    // Derived/runtime-only fields are deliberately excluded from Viper's
    // configuration surface with mapstructure:"-". They are still exported
    // so the rest of the application can consume the normalized value, but
    // must not appear in generated docs or .env.example.
    if (match[3] === "-") continue;
    fields.push({ field: match[1], type: match[2], key: match[3] });
  }
  return fields;
}

export function parseDefaults(source) {
  const defaults = new Map();
  const pattern =
    /envconfig\.Default\{Key:\s*"([^"]+)",\s*Value:\s*((?:"(?:\\.|[^"\\])*")|(?:[^}\n]+))\}/g;
  for (const match of source.matchAll(pattern)) {
    defaults.set(match[1], match[2].trim());
  }
  return defaults;
}

function displayDefault(raw) {
  if (raw === undefined) return "Go zero value";
  if (raw === '""') return "Empty";
  return `\`${literalDefault(raw).replaceAll("|", "\\|")}\``;
}

function displayType(goType) {
  return (
    {
      bool: "boolean",
      int: "integer",
      int32: "integer",
      int64: "integer",
      float64: "number",
      string: "string",
    }[goType] ?? goType
  );
}

const sensitiveKeys = new Set([
  "astronomer_encryption_key",
  "astronomer_internal_psk",
  "astronomer_bootstrap_password",
  "database_url",
  "delivery_source_proxy_url",
  "github_client_secret",
  "google_client_secret",
  "extension_bundle_trusted_key",
  "manifest_signing_secret",
  "oidc_client_secret",
  "otel_exporter_otlp_headers",
  "redis_url",
  "secret_key",
]);

export function render(source) {
  const fields = parseFields(source);
  const defaults = parseDefaults(source);
  const duplicateKeys = fields
    .map((field) => field.key)
    .filter((key, index, keys) => keys.indexOf(key) !== index);
  if (duplicateKeys.length > 0) {
    throw new Error(
      `duplicate mapstructure keys: ${[...new Set(duplicateKeys)].join(", ")}`,
    );
  }
  for (const key of defaults.keys()) {
    if (!fields.some((field) => field.key === key)) {
      throw new Error(`default ${key} has no Config field`);
    }
  }
  const bindings = new Set(
    [...source.matchAll(/envconfig\.BindEnv\(v,([\s\S]*?)\); err/g)].flatMap(
      (match) => [...match[1].matchAll(/"([^"]+)"/g)].map((item) => item[1]),
    ),
  );
  for (const key of bindings) {
    if (!fields.some((field) => field.key === key)) {
      throw new Error(`binding ${key} has no Config field`);
    }
  }
  for (const { key } of fields) {
    if (!bindings.has(key) && !defaults.has(key)) {
      throw new Error(
        `Config field ${key} has neither an environment binding nor a default`,
      );
    }
  }

  const rows = fields.map(({ field, type, key }) => {
    const env = key.toUpperCase();
    const sensitive = sensitiveKeys.has(key) ? "Yes" : "No";
    return `| \`${env}\` | \`${field}\` | ${displayType(type)} | ${displayDefault(defaults.get(key))} | ${sensitive} |`;
  });
  return `# Configuration reference

<!-- Generated by scripts/generate-config-docs.mjs from internal/config/config.go. Do not edit by hand. -->

Astronomer reads these values once at process startup. Environment variable names
are the uppercase form of the canonical configuration key. A “Go zero value”
means no application default is registered; deployment manifests or the
operator must set the value when the feature requires it.

Sensitive values must come from a Kubernetes Secret or an equivalent secret
store. Do not place them in chart values, command output, or support bundles.
Production-specific invariants are enforced at startup by
\`internal/config/production.go\`.

| Environment variable | Config field | Type | Application default | Sensitive |
|---|---|---|---|---|
${rows.join("\n")}

## Maintenance

The same generator owns \`.env.example\`: configuration fields and defaults
come from this schema, standalone server-mode inputs from \`cmd/server/main.go\`,
and the development proxy target from \`frontend/vite.config.ts\`.

Change the owning source, then run:

\`\`\`bash
make config-docs
make config-docs-check
\`\`\`
`;
}

export function renderEnvironment(source, serverSource, viteSource) {
  const defaults = parseDefaults(source);
  const fields = parseFields(source);
  const lines = fields.map(({ key, type }) => {
    const raw = defaults.get(key);
    let value;
    if (raw === undefined)
      value = type === "bool" ? "false" : type === "string" ? "" : "0";
    else value = literalDefault(raw);
    // Credentials without a registered local default stay empty; never mint
    // working signing/encryption keys into a checked-in example.
    return `${key.toUpperCase()}=${value === "" ? "" : JSON.stringify(String(value))}`;
  });
  const canonical = new Set(fields.map(({ key }) => key.toUpperCase()));
  const auxiliary = [
    ...new Set(
      [...serverSource.matchAll(/os\.Getenv\("([A-Z0-9_]+)"\)/g)].map(
        (match) => match[1],
      ),
    ),
  ]
    .filter((key) => !canonical.has(key))
    .sort();
  const proxy = viteSource.match(
    /process\.env\.BACKEND_URL\s*\?\?\s*['"]([^'"]+)['"]/,
  )?.[1];
  if (!proxy) throw new Error("cannot resolve Vite BACKEND_URL default");
  return `# Generated by scripts/generate-config-docs.mjs; do not edit by hand.
# Local application defaults, NOT production credentials or a Compose override.
# Copy to .env and load explicitly for a native server process. Compose owns
# its container environment in deploy/docker-compose.yml.
# Set SECRET_KEY, ASTRONOMER_ENCRYPTION_KEY and ASTRONOMER_INTERNAL_PSK
# using fresh local keys before starting authenticated services.
# Empty optional values require configuration when their feature is enabled.

${lines.join("\n")}

# Standalone proxy/server-mode inputs (cmd/server/main.go); opt-in only.
${auxiliary.map((key) => `${key}=`).join("\n")}

# Vite development proxy (frontend/vite.config.ts).
BACKEND_URL=${JSON.stringify(proxy)}
`;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const source = fs.readFileSync(sourcePath, "utf8");
  const outputs = new Map([
    [outputPath, render(source)],
    [
      environmentPath,
      renderEnvironment(
        source,
        fs.readFileSync(path.join(root, "cmd/server/main.go"), "utf8"),
        fs.readFileSync(path.join(root, "frontend/vite.config.ts"), "utf8"),
      ),
    ],
  ]);
  for (const [file, expected] of outputs) {
    if (process.argv.includes("--write")) {
      fs.writeFileSync(file, expected);
      console.log(`wrote ${path.relative(root, file)}`);
    } else if (
      !fs.existsSync(file) ||
      fs.readFileSync(file, "utf8") !== expected
    ) {
      console.error(
        `${path.relative(root, file)} is stale; run make config-docs`,
      );
      process.exitCode = 1;
    } else console.log(`${path.relative(root, file)} is current`);
  }
}
