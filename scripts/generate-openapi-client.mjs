#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const requireFromFrontend = createRequire(
  path.join(repoRoot, "frontend/package.json"),
);
const yaml = requireFromFrontend("js-yaml");
const args = new Set(process.argv.slice(2));
const write = args.has("--write");
const check = args.has("--check");
if (write === check) {
  console.error(
    "Usage: node scripts/generate-openapi-client.mjs --write|--check",
  );
  process.exit(2);
}

const spec = yaml.load(
  fs.readFileSync(path.join(repoRoot, "docs/openapi.yaml"), "utf8"),
);
const outputPath = path.join(
  repoRoot,
  "frontend/src/lib/api/generated/client.ts",
);
const methods = new Set([
  "get",
  "put",
  "post",
  "delete",
  "patch",
  "head",
  "options",
  "trace",
]);

function resolve(ref) {
  return ref
    .slice(2)
    .split("/")
    .map((part) => part.replace(/~1/g, "/").replace(/~0/g, "~"))
    .reduce((node, part) => node?.[part], spec);
}
function resolved(value) {
  return value?.$ref ? resolved(resolve(value.$ref)) : value;
}

const operations = [];
for (const [routePath, pathItemRaw] of Object.entries(spec.paths ?? {})) {
  const pathItem = resolved(pathItemRaw) ?? {};
  for (const [method, operationRaw] of Object.entries(pathItem)) {
    if (!methods.has(method.toLowerCase())) continue;
    const operation = resolved(operationRaw) ?? {};
    if (!operation.operationId)
      throw new Error(
        `${method.toUpperCase()} ${routePath} has no operationId`,
      );
    const parameters = [
      ...(Array.isArray(pathItem.parameters) ? pathItem.parameters : []),
      ...(Array.isArray(operation.parameters) ? operation.parameters : []),
    ]
      .map(resolved)
      .filter(Boolean);
    const requiredArgs =
      parameters.some((parameter) => parameter.required === true) ||
      resolved(operation.requestBody)?.required === true;
    const responseContent = Object.entries(operation.responses ?? {})
      .filter(([status]) => /^2\d\d$/.test(status))
      .flatMap(([, response]) =>
        Object.entries(resolved(response)?.content ?? {}),
      );
    const responseMedia = responseContent.map(([media]) => media);
    const responseType =
      responseContent.some(([, content]) => resolved(content?.schema)?.format === "binary") ||
      responseMedia.some((media) =>
        ["application/octet-stream", "application/zip"].includes(media),
      )
      ? "blob"
      : responseMedia.some(
            (media) =>
              media.includes("yaml") ||
              media === "text/csv" ||
              media === "text/plain",
          )
        ? "text"
        : "json";
    operations.push({
      id: operation.operationId,
      method: method.toUpperCase(),
      path: routePath,
      pathParameters: parameters
        .filter((parameter) => parameter.in === "path")
        .map((parameter) => parameter.name),
      responseType,
      requiredArgs,
    });
  }
}
operations.sort((a, b) => a.id.localeCompare(b.id));
const seen = new Set();
for (const operation of operations) {
  if (seen.has(operation.id))
    throw new Error(`Duplicate operationId ${operation.id}`);
  seen.add(operation.id);
}

const lines = [
  "// Generated by scripts/generate-openapi-client.mjs from docs/openapi.yaml.",
  "// Do not edit by hand. This module intentionally returns raw wire casing.",
  "",
  "import type { AxiosRequestConfig, AxiosResponseHeaders, RawAxiosResponseHeaders } from 'axios';",
  "import api from '@/lib/api/transport';",
  "import type { OpenAPIOperationId, OpenAPIOperations } from '@/types/openapi.generated';",
  "",
  "export interface OpenAPIRequestOptions {",
  "  signal?: AbortSignal;",
  "  headers?: Record<string, string>;",
  "  timeoutMs?: number;",
  "}",
  "",
  "export interface OpenAPIResponse<T> {",
  "  data: T;",
  "  headers: RawAxiosResponseHeaders | AxiosResponseHeaders;",
  "  status: number;",
  "}",
  "",
  "type OperationArguments<K extends OpenAPIOperationId> =",
  "  OpenAPIOperations[K]['arguments'] extends Record<string, never>",
  "    ? Record<string, unknown>",
  "    : OpenAPIOperations[K]['arguments'];",
  "",
  "export type OpenAPIArguments<K extends OpenAPIOperationId> =",
  "  OperationArguments<K> & OpenAPIRequestOptions;",
  "",
  "interface OperationMetadata {",
  "  method: string;",
  "  path: string;",
  "  pathParameters: readonly string[];",
  "  responseType: 'json' | 'text' | 'blob';",
  "}",
  "",
  "export const operationMetadata = {",
];
for (const operation of operations) {
  lines.push(
    `  ${JSON.stringify(operation.id)}: { method: ${JSON.stringify(operation.method)}, path: ${JSON.stringify(operation.path)}, pathParameters: ${JSON.stringify(operation.pathParameters)}, responseType: ${JSON.stringify(operation.responseType)} },`,
  );
}
lines.push(
  "} as const satisfies Record<OpenAPIOperationId, OperationMetadata>;",
);
lines.push("");
lines.push("export async function executeOpenAPIOperationWithResponse<K extends OpenAPIOperationId>(");
lines.push("  operationId: K,");
lines.push("  args: OpenAPIArguments<K>,");
lines.push("): Promise<OpenAPIResponse<OpenAPIOperations[K]['response']>> {");
lines.push("  const metadata = operationMetadata[operationId];");
lines.push(
  "  const values = args as OpenAPIRequestOptions & { path?: Record<string, unknown>; query?: Record<string, unknown>; headerParams?: Record<string, unknown>; body?: unknown };",
);
lines.push("  let url: string = metadata.path;");
lines.push("  for (const name of metadata.pathParameters) {");
lines.push("    const value = values.path?.[name];");
lines.push(
  '    if (value === undefined || value === null || value === "") throw new Error(`Missing path parameter ${name} for ${String(operationId)}`);',
);
lines.push(
  "    url = url.replace(`{${name}}`, encodeURIComponent(String(value)));",
);
lines.push("  }");
lines.push(
  "  const parameterHeaders = Object.fromEntries(Object.entries(values.headerParams ?? {}).filter(([, value]) => value !== undefined).map(([name, value]) => [name, String(value)]));",
);
lines.push("  const config = {");
lines.push(
  "    // OpenAPI paths are already root-absolute. Override the shared transport's",
);
lines.push(
  "    // /api/v1 base so generated requests never become /api/v1/api/v1/... and",
);
lines.push("    // non-management paths such as /scim/v2 remain exact.");
lines.push(
  "    baseURL: '', method: metadata.method, url, params: values.query, data: values.body, signal: values.signal, timeout: values.timeoutMs,",
);
lines.push(
  "    headers: { ...parameterHeaders, ...values.headers }, responseType: metadata.responseType,",
);
lines.push("  } as AxiosRequestConfig;");
lines.push("  const response = await api.request(config);");
lines.push("  return { data: response.data as OpenAPIOperations[K]['response'], headers: response.headers, status: response.status };");
lines.push("}");
lines.push("");
lines.push("export async function executeOpenAPIOperation<K extends OpenAPIOperationId>(");
lines.push("  operationId: K,");
lines.push("  args: OpenAPIArguments<K>,");
lines.push("): Promise<OpenAPIOperations[K]['response']> {");
lines.push("  return (await executeOpenAPIOperationWithResponse(operationId, args)).data;");
lines.push("}");
lines.push("");
for (const operation of operations) {
  const optional = operation.requiredArgs ? "" : "?";
  const fallback = operation.requiredArgs
    ? ""
    : " ?? ({} as OpenAPIArguments<typeof operationId>)";
  lines.push(
    `export function ${operation.id}(args${optional}: OpenAPIArguments<${JSON.stringify(operation.id)}>) {`,
  );
  lines.push(`  const operationId = ${JSON.stringify(operation.id)} as const;`);
  lines.push(`  return executeOpenAPIOperation(operationId, args${fallback});`);
  lines.push("}");
  lines.push("");
}
const generated = `${lines.join("\n").trimEnd()}\n`;
if (write) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, generated);
  process.exit(0);
}
const current = fs.existsSync(outputPath)
  ? fs.readFileSync(outputPath, "utf8")
  : "";
if (current !== generated) {
  console.error(
    "Generated OpenAPI frontend client is stale. Run scripts/generate-openapi-client.mjs --write.",
  );
  process.exit(1);
}
console.log("Generated OpenAPI frontend client is current.");
